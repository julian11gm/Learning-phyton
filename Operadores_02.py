print(type(5)) # tipo int
print(type(1.5)) # tipo float
print(type(3 + 1j)) # tipo complex
print (type(True)) # tipo bool


#Inicio de las clases operadores

# Los basicos operadores aritméticos
print(5 + 2) # suma
print(5 - 2) # resta
print(5 * 2) # multiplicación
print(5 / 2) # división
print(5 // 2) # división entera
print(5 % 2) # módulo
print(5 ** 2) # potencia

#Tambien con algunos operadores podemos utilizar para cadenas de texto
print("hola" + "julio") # concatenación
print("hola" * 3) # repetición

#Operadores comparativos
print(5>2) # mayor que
print(5<2) # menor que
print(5>=2) # mayor o igual que
print(5<=2) # menor o igual que
print(5==2) # igual que

#Tambien se utilizan con caracteres
print( "lebrone" > "madona") # mayor que
#Tambien se utilizan con Len
print(len("lebrone") > len("madona")) # mayor que


#Operadores logicos
print(5>2 and 5<10) # and
print(5>2 or 5<10) # or
print(not(5>2)) # not


